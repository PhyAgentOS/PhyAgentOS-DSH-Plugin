#!/usr/bin/env node
/**
 * Build the browser half of the plugin as a DSH client-module bundle.
 *
 * DSH loads client plugins as classic scripts that call
 * `window.__ModuleLoader__.load({ id, factory })`; every platform module the
 * bundle imports is resolved through the injected `require`, never a browser
 * import. We therefore emit CommonJS and wrap it in that factory instead of
 * vendoring the harness's full client build preset.
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const entry = join(root, 'packages/skill/client/index.tsx')
const outDir = join(root, 'packages/skill/lib')
const temporary = join(outDir, 'client.bundle.cjs')
const target = join(outDir, 'client.js')
const packageName = '@x-era/dsh-forge-skill'

/** Specifiers the shell's frozen module table resolves (packages/client/web/src/platform.ts). */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

await mkdir(outDir, { recursive: true })
await build({
  entryPoints: [entry],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: PLATFORM_MODULES,
  outfile: temporary,
  logLevel: 'warning',
  legalComments: 'none',
})

const code = await readFile(temporary, 'utf8')
const wrapped = [
  '/* Generated by scripts/build-client.mjs — do not edit. */',
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(packageName)}, factory: (require) => {`,
  '  const module = { exports: {} };',
  '  const exports = module.exports;',
  code,
  '  return module.exports;',
  '} });',
  '',
].join('\n')
await writeFile(target, wrapped)
await rm(temporary, { force: true })
console.log(`client bundle: ${target} (${wrapped.length} bytes)`)
